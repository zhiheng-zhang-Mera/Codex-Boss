const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const moduleAt = file => require('../dist-electron/electron/' + file);
const { MainCommander } = moduleAt('commander/main-commander');
const { StateStore } = moduleAt('store');
const { RuntimeRegistry } = moduleAt('commander/runtime-registry');
const { BudgetManager } = moduleAt('commander/budget-manager');
const { RoleRouter } = moduleAt('commander/role-router');
const { Scheduler } = moduleAt('commander/scheduler');
const { ContextManager } = moduleAt('commander/context-manager');
const { ExecutionGate } = moduleAt('commander/execution-gate');
const { TaskLedger } = moduleAt('commander/task-ledger');
const { CodexCliRuntime } = moduleAt('runtimes/codex/codex-cli-runtime');
const root = path.resolve(__dirname, '..', 'artifacts', 'finalization-' + randomUUID());
fs.mkdirSync(root, { recursive: true });
const evidence = { kind: 'LIVE_PROVIDER', scope: 'Real Codex CLI final synthesis of controlled accepted source artifacts', root, status: 'RUNNING', startedAt: new Date().toISOString() };
(async () => {
  const file = path.join(root, 'state.json'); const store = new StateStore(file);
  const registry = new RuntimeRegistry(); const budgets = new BudgetManager();
  registry.register(new CodexCliRuntime(root));
  const ledger = new TaskLedger(path.join(root, '.boss', 'tasks'));
  const create = state => new MainCommander(state, registry, new Scheduler(), new RoleRouter(registry, budgets), budgets, new ContextManager(), new ExecutionGate(), ledger);
  const commander = create(store);
  const task = commander.createTask({ title: 'Live final synthesis', objective: 'Use the accepted arithmetic fact and completion marker. Reply exactly: 2 + 3 = 5. BOSS_S5_SYNTHESIS_OK', providerIds: ['chatgpt', 'gemini'], finalizationPolicy: 'CODEX_REQUIRED' });
  evidence.taskId = task.id;
  const checkpoint = store.beginDispatch(task.id, 1, task.providerIds).checkpoint;
  store.markDispatchCollecting(checkpoint.id, task.providerIds);
  const runs = store.runsForTask(task.id);
  store.captureArtifact(runs[0].id, 'The verified arithmetic fact is 2 + 3 = 5.', 'local:controlled-arithmetic');
  store.captureArtifact(runs[1].id, 'The requested completion marker is BOSS_S5_SYNTHESIS_OK.', 'local:controlled-marker');
  fs.writeFileSync(path.join(root, 'result.json'), JSON.stringify(evidence, null, 2));
  console.log('LIVE_FINALIZATION_STARTED ' + root);
  const final = await commander.finalizeTask(task.id);
  evidence.final = final; evidence.usage = ledger.load(task.id)?.usage;
  if (final?.source !== 'codex_synthesis' || final.content !== '2 + 3 = 5. BOSS_S5_SYNTHESIS_OK' || final.sourceArtifactIds.length !== 2) throw Error('Final answer did not satisfy exact synthesis contract');
  const restored = new StateStore(file);
  await create(restored).finalizeTask(task.id);
  evidence.restoredFinalId = restored.finalResponseForTask(task.id)?.id;
  evidence.modelCallsAfterRestart = ledger.load(task.id)?.usage.modelCalls;
  if (evidence.restoredFinalId !== final.id || evidence.usage.modelCalls !== 1 || evidence.modelCallsAfterRestart !== 1) throw Error('Restart duplicated finalization');
  evidence.status = 'PASS';
})().catch(error => { evidence.status = 'FAILED'; evidence.error = String(error); process.exitCode = 1; }).finally(() => {
  evidence.completedAt = new Date().toISOString();
  fs.writeFileSync(path.join(root, 'result.json'), JSON.stringify(evidence, null, 2));
  console.log(JSON.stringify({ root, status: evidence.status, error: evidence.error, final: evidence.final?.content }, null, 2));
});
