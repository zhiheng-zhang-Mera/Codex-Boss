const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { execFileSync } = require('node:child_process');
const moduleAt = file => require('../dist-electron/electron/' + file);
const { MainCommander } = moduleAt('commander/main-commander');
const { StateStore } = moduleAt('store');
const { RuntimeRegistry } = moduleAt('commander/runtime-registry');
const { BudgetManager } = moduleAt('commander/budget-manager');
const { RoleRouter } = moduleAt('commander/role-router');
const { Scheduler } = moduleAt('commander/scheduler');
const { ContextManager } = moduleAt('commander/context-manager');
const { ExecutionGate } = moduleAt('commander/execution-gate');
const { TaskLedger } = moduleAt('commander/task-ledger');
const { CodexCliRuntime } = moduleAt('runtimes/codex/codex-cli-runtime');
const { runCheck } = moduleAt('engineering/verification');
const root = path.resolve(__dirname, '..', 'artifacts', 'engineering-' + randomUUID());
fs.mkdirSync(root, { recursive: true });
const evidence = { kind: 'LIVE_CLI_ENGINEERING', root, status: 'RUNNING', startedAt: new Date().toISOString() };
(async () => {
  fs.writeFileSync(path.join(root, '.gitignore'), '.boss/\nresult.json\n');
  fs.writeFileSync(path.join(root, 'tasks.md'), 'Refactor sum.cjs so addition works for positive and negative numbers. Preserve the public function signature. Keep sum.test.cjs unchanged. Run tests and report actual results.');
  fs.writeFileSync(path.join(root, 'sum.cjs'), 'module.exports=(a,b)=>a-b;');
  fs.writeFileSync(path.join(root, 'sum.test.cjs'), "const test=require('node:test');const assert=require('node:assert/strict');test('positive sum',()=>assert.equal(require('./sum.cjs')(2,3),5));test('negative sum',()=>assert.equal(require('./sum.cjs')(-2,-3),-5));");
  const git = (...args) => execFileSync('git', args, { cwd: root, windowsHide: true });
  git('init'); git('add', '.'); git('-c', 'user.name=Acceptance', '-c', 'user.email=acceptance@example.invalid', 'commit', '-m', 'acceptance fixture');
  evidence.baseline = await runCheck(root, { kind: 'test', files: ['sum.test.cjs'] });
  const store = new StateStore(path.join(root, '.boss', 'state.json')); const registry = new RuntimeRegistry(); const budgets = new BudgetManager();
  registry.register(new CodexCliRuntime(path.join(root, '.boss')));
  const ledger = new TaskLedger(path.join(root, '.boss', 'tasks'));
  const commander = new MainCommander(store, registry, new Scheduler(), new RoleRouter(registry, budgets), budgets, new ContextManager(), new ExecutionGate(), ledger);
  const task = commander.createTask({ title: 'Live engineering acceptance', objective: '按照 tasks.md 重构这个项目并确保测试通过', providerIds: ['chatgpt'], appMode: 'work' });
  evidence.taskId = task.id; fs.writeFileSync(path.join(root, 'result.json'), JSON.stringify(evidence, null, 2));
  console.log('LIVE_ENGINEERING_STARTED ' + root);
  await commander.executePlan(task.id, root);
  evidence.task = store.snapshot().tasks.find(item => item.id === task.id);
  evidence.finalResponse = store.finalResponseForTask(task.id);
  evidence.ledger = ledger.load(task.id);
  const workspace = evidence.ledger.workspace?.path || root;
  evidence.finalCheck = await runCheck(workspace, { kind: 'test', files: ['sum.test.cjs'] });
  evidence.source = fs.readFileSync(path.join(workspace, 'sum.cjs'), 'utf8');
  if (!evidence.finalResponse || !evidence.finalCheck.passed || evidence.baseline.passed) throw Error('Live engineering acceptance incomplete');
  evidence.status = 'PASS';
})().catch(error => { evidence.status = 'FAILED'; evidence.error = String(error); process.exitCode = 1; }).finally(() => { fs.writeFileSync(path.join(root, 'result.json'), JSON.stringify(evidence, null, 2)); console.log(JSON.stringify({ root, status: evidence.status, error: evidence.error, final: evidence.finalResponse?.content }, null, 2)); });
