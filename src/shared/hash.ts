/**
 * Tiny dependency-free SHA-256 (Work Unit 1). Pure TypeScript so both the
 * renderer bundle and the electron main process hash identically without
 * importing `node:crypto`, which the renderer cannot use.
 *
 * Verified against Node's crypto in tests/unit/workbook-hash.test.ts.
 */

